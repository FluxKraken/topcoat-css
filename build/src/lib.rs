//! Compile component-local `css!` modules into a stylesheet from `build.rs`.
//!
//! ```no_run
//! fn main() -> Result<(), topcoat_css_build::BuildError> {
//!     topcoat_css_build::BuildConfig::new().render()?;
//!     Ok(())
//! }
//! ```

mod scanner;

use std::{
    collections::BTreeSet,
    env, fmt, fs,
    path::{Path, PathBuf},
};
use topcoat_css_core::compiler;
use topcoat_css_core::{MANIFEST_ENV, MANIFEST_VERSION, Manifest, Module, STYLESHEET_ENV};

/// A source, CSS, configuration, or filesystem error with human-readable context.
#[derive(Debug)]
pub struct BuildError(String);

impl fmt::Display for BuildError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}
impl std::error::Error for BuildError {}
impl From<String> for BuildError {
    fn from(message: String) -> Self {
        Self(message)
    }
}

type Result<T> = std::result::Result<T, BuildError>;

/// Configure source collection. By default, recursively scans `src/` for `css!`.
/// Collection is lexical: it does not expand macros or evaluate `#[cfg]`.
#[derive(Debug, Clone)]
pub struct BuildConfig {
    manifest_dir: Option<PathBuf>,
    out_dir: Option<PathBuf>,
    namespace: Option<String>,
    sources: Vec<PathBuf>,
    macro_names: BTreeSet<String>,
    minify: bool,
}

impl Default for BuildConfig {
    fn default() -> Self {
        Self {
            manifest_dir: None,
            out_dir: None,
            namespace: None,
            sources: vec![PathBuf::from("src")],
            macro_names: BTreeSet::from(["css".into()]),
            minify: false,
        }
    }
}

/// Paths to the artifacts generated by a successful build.
#[derive(Debug)]
pub struct BuildOutput {
    pub stylesheet: PathBuf,
    pub manifest: PathBuf,
    pub module_count: usize,
}

impl BuildConfig {
    pub fn new() -> Self {
        Self::default()
    }

    /// Override `CARGO_MANIFEST_DIR`. Source paths must remain within this directory.
    pub fn manifest_dir(mut self, path: impl Into<PathBuf>) -> Self {
        self.manifest_dir = Some(path.into());
        self
    }

    /// Override Cargo's `OUT_DIR`, primarily for testing or custom build drivers.
    pub fn out_dir(mut self, path: impl Into<PathBuf>) -> Self {
        self.out_dir = Some(path.into());
        self
    }

    /// Override the package-name namespace used in scoped name hashes.
    pub fn namespace(mut self, name: impl Into<String>) -> Self {
        self.namespace = Some(name.into());
        self
    }

    /// Add a source directory or Rust file. Paths are relative to the package root.
    /// Use this for examples, tests, or nonstandard module directories.
    pub fn source(mut self, path: impl Into<PathBuf>) -> Self {
        self.sources.push(path.into());
        self
    }

    /// Remove the default `src/` root before supplying explicit sources.
    pub fn clear_sources(mut self) -> Self {
        self.sources.clear();
        self
    }

    /// Also collect a renamed macro, e.g. `use topcoat_css::css as component_css`.
    pub fn macro_name(mut self, name: impl Into<String>) -> Self {
        self.macro_names.insert(name.into());
        self
    }

    /// Minify printed whitespace. Rules are never reordered or merged across modules.
    pub fn minify(mut self, enabled: bool) -> Self {
        self.minify = enabled;
        self
    }

    /// Compile and publish Cargo environment/rebuild directives.
    /// Watches source directories so added and deleted files trigger regeneration.
    pub fn render(self) -> Result<BuildOutput> {
        self.run(true)
    }

    /// Compile without printing Cargo directives. Useful for tests and other drivers.
    /// Supply `manifest_dir`, `out_dir`, and `namespace` to avoid environment defaults.
    pub fn compile(self) -> Result<BuildOutput> {
        self.run(false)
    }

    fn run(self, cargo: bool) -> Result<BuildOutput> {
        let manifest_dir = resolve(self.manifest_dir, "CARGO_MANIFEST_DIR")?;
        let manifest_dir = canonicalize(&manifest_dir)?;
        let out_dir = resolve(self.out_dir, "OUT_DIR")?;
        fs::create_dir_all(&out_dir).map_err(|e| io_error(&out_dir, e))?;
        let out_dir = canonicalize(&out_dir)?;
        let namespace = self
            .namespace
            .or_else(|| env::var("CARGO_PKG_NAME").ok())
            .ok_or_else(|| BuildError("set namespace() or CARGO_PKG_NAME".into()))?;
        let mut files = BTreeSet::new();
        for root in self.sources {
            let path = manifest_dir.join(root);
            let path = canonicalize(&path)?;
            if !path.starts_with(&manifest_dir) {
                return Err(BuildError(format!(
                    "source {} must be inside the package root",
                    path.display()
                )));
            }
            if out_dir.starts_with(&path) {
                return Err(BuildError(format!(
                    "source {} contains the output directory; scan a source directory such as src/",
                    path.display()
                )));
            }
            if cargo {
                println!("cargo:rerun-if-changed={}", utf8(&path)?);
            }
            scanner::collect_files(&path, &mut files)?;
        }
        let mut modules = Vec::new();
        let mut css = String::from("/* Generated by topcoat-css. Do not edit. */\n");
        for file in files {
            let source = fs::read_to_string(&file).map_err(|e| io_error(&file, e))?;
            let relative = utf8(
                file.strip_prefix(&manifest_dir)
                    .expect("checked source root"),
            )?
            .replace('\\', "/");
            let inputs = scanner::scan(&source, &self.macro_names)
                .map_err(|e| BuildError(format!("{}: {e}", file.display())))?;
            for (index, input) in inputs.into_iter().enumerate() {
                let compiled =
                    compiler::compile(&input.css, &namespace, &relative, index, self.minify)
                        .map_err(|e| {
                            BuildError(format!(
                                "{}:{}:{}: {e}",
                                file.display(),
                                input.line,
                                input.column
                            ))
                        })?;
                css.push_str(&compiled.css);
                css.push('\n');
                modules.push(Module {
                    file: utf8(&file)?.to_owned(),
                    line: input.line,
                    column: input.column,
                    fingerprint: input.fingerprint,
                    fields: compiled.fields,
                });
            }
        }
        let stylesheet = out_dir.join("topcoat.css");
        let manifest_path = out_dir.join("topcoat-css-manifest.json");
        let manifest = Manifest {
            version: MANIFEST_VERSION,
            modules,
        };
        let json = serde_json::to_vec_pretty(&manifest).map_err(|e| BuildError(e.to_string()))?;
        write_if_changed(&stylesheet, css.as_bytes())?;
        write_if_changed(&manifest_path, &json)?;
        if cargo {
            println!("cargo:rustc-env={STYLESHEET_ENV}={}", utf8(&stylesheet)?);
            println!("cargo:rustc-env={MANIFEST_ENV}={}", utf8(&manifest_path)?);
        }
        Ok(BuildOutput {
            stylesheet,
            manifest: manifest_path,
            module_count: manifest.modules.len(),
        })
    }
}

fn resolve(path: Option<PathBuf>, variable: &str) -> Result<PathBuf> {
    path.or_else(|| env::var_os(variable).map(PathBuf::from))
        .ok_or_else(|| {
            BuildError(format!(
                "{variable} is unavailable; run from build.rs or supply the path explicitly"
            ))
        })
}
fn canonicalize(path: &Path) -> Result<PathBuf> {
    fs::canonicalize(path).map_err(|e| io_error(path, e))
}
fn io_error(path: &Path, error: std::io::Error) -> BuildError {
    BuildError(format!("{}: {error}", path.display()))
}
fn utf8(path: &Path) -> Result<&str> {
    let value = path
        .to_str()
        .ok_or_else(|| BuildError(format!("path is not UTF-8: {}", path.display())))?;
    if value.contains(['\n', '\r']) {
        return Err(BuildError("paths cannot contain newlines".into()));
    }
    Ok(value)
}
fn write_if_changed(path: &Path, bytes: &[u8]) -> Result<()> {
    if fs::read(path).is_ok_and(|current| current == bytes) {
        return Ok(());
    }
    fs::write(path, bytes).map_err(|e| io_error(path, e))
}
